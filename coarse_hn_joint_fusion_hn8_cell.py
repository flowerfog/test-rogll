def _clean(value):
    if isinstance(value, dict):
        return {str(key): _clean(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_clean(item) for item in value]
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating, float)):
        return float(value) if np.isfinite(value) else None
    if isinstance(value, (np.bool_,)):
        return bool(value)
    return value


def _write_json(path, payload):
    path.write_text(
        json.dumps(_clean(payload), indent=2, allow_nan=False), encoding="utf-8"
    )


def _bootstrap(path, marker, name):
    if not path.is_file():
        raise FileNotFoundError(path)
    source = path.read_text(encoding="utf-8")
    if marker not in source:
        raise RuntimeError(f"Cannot find {marker!r} in {path}")
    namespace = {"__name__": name, "__file__": str(path)}
    exec(compile(source.split(marker, 1)[0], str(path), "exec"), namespace)
    return namespace


def _ensemble_tournament(models, values):
    count = len(values)
    if count == 1:
        return np.ones(1, np.float64)
    sums = np.zeros(count, np.float64)
    seen = np.zeros(count, np.int64)
    left_all, right_all = np.triu_indices(count, 1)
    for start in range(0, len(left_all), PAIR_BATCH):
        left = left_all[start : start + PAIR_BATCH]
        right = right_all[start : start + PAIR_BATCH]
        delta = values[left] - values[right]
        probability = np.mean(
            np.vstack([model.predict(delta) for model in models]), axis=0
        )
        sums[left] += probability
        sums[right] += 1.0 - probability
        seen[left] += 1
        seen[right] += 1
    return sums / np.maximum(seen, 1)


def _metrics(frame, prediction):
    truth = frame[TRUTH].to_numpy(np.float64)
    error = prediction - truth
    error2 = error ** 2
    bywell = pd.DataFrame({"well": frame["well"].astype(str), "e2": error2})
    bywell = bywell.groupby("well", sort=False)["e2"].mean().pow(0.5)
    far = frame["md_since"].to_numpy(np.float64) > 2000.0
    return {
        "rows": int(len(frame)),
        "wells": int(frame["well"].nunique()),
        "exact_sse": float(error2.sum()),
        "rmse": float(np.sqrt(np.mean(error2))),
        "mae": float(np.mean(np.abs(error))),
        "median_well_rmse": float(bywell.median()),
        "p95_well_rmse": float(bywell.quantile(0.95)),
        "max_well_rmse": float(bywell.max()),
        "far_gt2000_rmse": float(np.sqrt(np.mean(error2[far]))),
    }


def _correlation(left, right):
    mask = np.isfinite(left) & np.isfinite(right)
    if mask.sum() < 2 or np.std(left[mask]) == 0 or np.std(right[mask]) == 0:
        return float("nan")
    return float(np.corrcoef(left[mask], right[mask])[0, 1])


def _distance_detrend(error, distance):
    output = np.empty_like(error, dtype=np.float64)
    bins = np.asarray([0.0, 500.0, 1000.0, 2000.0, np.inf])
    for lower, upper in zip(bins[:-1], bins[1:]):
        mask = (distance > lower) & (distance <= upper)
        output[mask] = error[mask] - np.mean(error[mask])
    return output


