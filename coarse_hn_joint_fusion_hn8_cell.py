def _fold1_hn_rows():
    if CACHE_FOLD1.is_file():
        return pd.read_parquet(CACHE_FOLD1)

    fold1_source = pd.read_parquet(V63_FOLD1)
    requested_wells = sorted(fold1_source["well"].astype(str).unique())
    data_root = Path(Q["DATA_ROOT"])
    all_wells = [
        path.name.split("__", 1)[0]
        for path in sorted((data_root / "train").glob("*__horizontal_well.csv"))
    ]
    folds = V["_stable_folds"](all_wells)
    fold_by_well = dict(zip(folds["well"].astype(str), folds["fold"].astype(int)))
    if any(fold_by_well.get(well) != 1 for well in requested_wells):
        raise RuntimeError("V63 Fold1 wells do not match stable Fold1")

    prior_records = []
    for well in all_wells:
        if fold_by_well[well] in (4, 5):
            try:
                prior_records.append(V["_load_record"](well))
            except Exception:
                pass
    if len(prior_records) < 307:
        raise RuntimeError(f"Only {len(prior_records)} Fold45 prior records")
    prior = V["_fit_prior"](prior_records, Q["SEGMENT_LENGTH_FT"])

    blocks = []
    failures = []
    for number, well in enumerate(requested_wells, 1):
        try:
            panel = H["_load_panel"](well)
            record = V["_load_record"](well)
            paths, _, _, _, segments, _ = Q["_candidate_union"](record, prior)
            if len(paths) != len(panel["features"]):
                raise RuntimeError(
                    f"candidate count changed: {len(paths)}/{len(panel['features'])}"
                )
            legal_rank = np.min(np.asarray(panel["arm_rank"], np.float64), axis=1)
            menu = np.argsort(legal_rank, kind="stable")[: min(MENU_SIZE, len(paths))]
            values = np.asarray(panel["features"][menu][:, columns], np.float32)
            values = np.nan_to_num(values, nan=0.0, posinf=12.0, neginf=-12.0)
            score = _ensemble_tournament(models, values)
            selected_index = int(menu[int(np.argmax(score))])
            prediction = B["_path_prediction"](
                record, prior, paths[selected_index], segments
            )
            eval_rows = np.asarray(record["eval_rows"], np.int64)
            blocks.append(
                pd.DataFrame(
                    {
                        "id": [f"{well}_{int(row)}" for row in eval_rows],
                        "well": well,
                        "row_idx": eval_rows,
                        HN: np.asarray(prediction[eval_rows], np.float32),
                    }
                )
            )
        except Exception as exc:
            failures.append({"well": well, "reason": repr(exc)})
        if number % 20 == 0 or number == len(requested_wells):
            print(
                f"HN8 Fold1 HN {number}/{len(requested_wells)} "
                f"success={len(blocks)} failures={len(failures)}",
                flush=True,
            )
    pd.DataFrame(failures).to_csv(OUT_DIR / "fold1_hn_failures.csv", index=False)
    if len(blocks) < 90:
        raise RuntimeError(f"Only {len(blocks)} Fold1 HN wells: {failures[:5]}")
    output = pd.concat(blocks, ignore_index=True)
    output.to_parquet(CACHE_FOLD1, index=False, compression="zstd")
    return output


def _read_v63(path, fold):
    frame = pd.read_parquet(path)
    required = {"id", "well", "row_idx", TRUTH, "md_since", PARENT, COARSE}
    missing = sorted(required.difference(frame.columns))
    if missing:
        raise RuntimeError(f"{path}: missing {missing}")
    frame = frame[list(required)].copy()
    frame["audit_fold"] = int(fold)
    return frame


