def _predict(frame, coarse_weight, hn_weight):
    base = frame[PARENT].to_numpy(np.float64)
    coarse = frame[COARSE].to_numpy(np.float64)
    hn = frame[HN].to_numpy(np.float64)
    return (
        (1.0 - coarse_weight - hn_weight) * base
        + coarse_weight * coarse
        + hn_weight * hn
    )


