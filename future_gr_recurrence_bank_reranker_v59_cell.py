"""Rerank a deployable raw-data lattice bank with future-GR self recurrence.

V58 established that non-local visits to the same candidate TVT carry causal
information about relative path drift.  V59 removes V58's truth-shaped path
family: every candidate is generated by the frozen V3 label-free beam.  Fold
4/5 fit the physical prior, 24 Fold-3 wells select only the recurrence dose,
the remaining Fold-3 wells confirm it, and Fold 2 is touched only after that
confirmation passes.  Fold 1 remains untouched.
"""

