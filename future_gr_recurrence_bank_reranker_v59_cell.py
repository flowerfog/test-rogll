def _record_cache(record, prior):
    scores, paths, segments = N._beam_bank_v3(record, prior, ARM)
    eval_rows = record["eval_rows"]
    sampled = eval_rows[::ROW_STRIDE]
    truth = record["truth"][eval_rows]
    distance = record["md"][eval_rows] - record["anchor_md"]
    far = distance > 2000.0
    gr = record["gr"][sampled]
    rolled_gr = np.roll(gr, max(len(gr) // 5, 1))
    recurrence = np.full(len(paths), np.nan, np.float64)
    rolled = np.full(len(paths), np.nan, np.float64)
    pairs = np.zeros(len(paths), np.int32)
    sse = np.full(len(paths), np.inf, np.float64)
    sae = np.full(len(paths), np.inf, np.float64)
    far_sse = np.full(len(paths), np.inf, np.float64)
    endpoint = np.full(len(paths), np.nan, np.float64)
    for index, path in enumerate(paths):
        prediction = B["_path_prediction"](record, prior, path, segments)[eval_rows]
        error = prediction - truth
        if not np.isfinite(error).all():
            continue
        sse[index] = float(np.sum(error * error))
        sae[index] = float(np.sum(np.abs(error)))
        far_sse[index] = float(np.sum(error[far] ** 2))
        endpoint[index] = float(prediction[-1])
        recurrence[index], pairs[index] = _recurrence_cost(
            record["md"][sampled], prediction[::ROW_STRIDE], gr, record["noise_scale"]
        )
        rolled[index], _ = _recurrence_cost(
            record["md"][sampled], prediction[::ROW_STRIDE], rolled_gr, record["noise_scale"]
        )
    valid_paths = np.isfinite(sse)
    if not valid_paths.any():
        raise RuntimeError(f"{record['well']}: no finite path predictions")
    return {
        "well": record["well"],
        "rows": int(len(eval_rows)),
        "far_rows": int(far.sum()),
        "scores": np.asarray(scores, np.float64),
        "recurrence": recurrence,
        "rolled": rolled,
        "pairs": pairs,
        "sse": sse,
        "sae": sae,
        "far_sse": far_sse,
        "endpoint": endpoint,
        "available_fraction": float(np.mean(np.isfinite(recurrence))),
    }


def _build(records, prior, label):
    output, failures = [], []
    for number, record in enumerate(records, 1):
        try:
            output.append(_record_cache(record, prior))
        except Exception as exc:
            failures.append({"well": record["well"], "reason": repr(exc)})
        if number % 10 == 0 or number == len(records):
            print(f"V59 bank {label} {number}/{len(records)} failures={len(failures)}", flush=True)
    pd.DataFrame(failures).to_csv(OUT_DIR / f"{label}_failures.csv", index=False)
    return output


def _select(item, dose, control):
    base = _robust_standardise(item["scores"])
    evidence = item["recurrence"] if control == "aligned" else item["rolled"]
    total = base + float(dose) * _robust_standardise(evidence)
    total[~np.isfinite(item["sse"])] = np.inf
    return int(np.argmin(total))


def _evaluate(cache, dose, control, variant):
    rows = []
    for item in cache:
        selected = _select(item, dose, control)
        oracle = int(np.argmin(item["sse"]))
        rows.append(
            {
                "well": item["well"],
                "variant": variant,
                "dose": float(dose),
                "control": control,
                "rows": item["rows"],
                "far_rows": item["far_rows"],
                "sse": float(item["sse"][selected]),
                "sae": float(item["sae"][selected]),
                "far_sse": float(item["far_sse"][selected]),
                "oracle_sse": float(item["sse"][oracle]),
                "selected_index": selected,
                "map_index": int(np.argmin(item["scores"])),
                "oracle_index": oracle,
                "selected_endpoint": float(item["endpoint"][selected]),
                "available_fraction": item["available_fraction"],
                "selected_pairs": int(item["pairs"][selected]),
            }
        )
    return pd.DataFrame(rows)


def _summary(frame):
    rows = int(frame["rows"].sum())
    far_rows = int(frame["far_rows"].sum())
    return {
        "rows": rows,
        "wells": int(frame["well"].nunique()),
        "exact_sse": float(frame["sse"].sum()),
        "rmse": float(np.sqrt(frame["sse"].sum() / max(rows, 1))),
        "mae": float(frame["sae"].sum() / max(rows, 1)),
        "far_gt2000_rmse": float(np.sqrt(frame["far_sse"].sum() / max(far_rows, 1))),
        "bank_oracle_rmse": float(np.sqrt(frame["oracle_sse"].sum() / max(rows, 1))),
        "mean_available_fraction": float(frame["available_fraction"].mean()),
        "selected_path_change_fraction": float(np.mean(frame["selected_index"] != frame["map_index"])),
        "median_selected_pairs": float(frame["selected_pairs"].median()),
    }


def _run_stage(cache, dose, label):
    aligned = _evaluate(cache, dose, "aligned", f"{label}_aligned")
    rolled = _evaluate(cache, dose, "rolled", f"{label}_rolled")
    baseline = _evaluate(cache, 0.0, "aligned", f"{label}_baseline")
    detail = pd.concat([baseline, aligned, rolled], ignore_index=True)
    detail.to_csv(OUT_DIR / f"{label}_bywell.csv", index=False)
    summary = pd.DataFrame(
        [
            {"variant": "baseline", **_summary(baseline)},
            {"variant": "aligned", **_summary(aligned)},
            {"variant": "rolled", **_summary(rolled)},
        ]
    )
    summary.to_csv(OUT_DIR / f"{label}_summary.csv", index=False)
    print(f"\nV59 {label.upper()}")
    print(summary.to_string(index=False), flush=True)
    return {row["variant"]: row for row in summary.to_dict("records")}


